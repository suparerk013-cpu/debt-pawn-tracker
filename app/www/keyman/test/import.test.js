function dbdFile(title, rows) {
  const aoa = [[title], ['ข้อมูลปีงบการเงิน 2563 - 2567'], [],
    ['หน่วย : บาท', '2563', '', '2564', '', '2565', '', '2566', '', '2567'],
    ['', 'จำนวนเงิน', '%เปลี่ยนแปลง', 'จำนวนเงิน', '%เปลี่ยนแปลง', 'จำนวนเงิน', '%เปลี่ยนแปลง', 'จำนวนเงิน', '%เปลี่ยนแปลง', 'จำนวนเงิน', '%เปลี่ยนแปลง']];
  rows.forEach((r) => {
    const line = [r[0]];
    r[1].forEach((v, i) => { line.push(v); line.push(r[2][i]); });
    aoa.push(line);
  });
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(aoa), 'Finance');
  return new Uint8Array(XLSX.write(wb, { type: 'array', bookType: 'xlsx' }));
}

